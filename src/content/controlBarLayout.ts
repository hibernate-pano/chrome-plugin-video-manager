/**
 * 控制条的**布局契约**：断点 + 各档的实测宽度需求。
 *
 * ⚠️ 为什么单独成文件：这个契约有**三个消费方**，而它们一旦各写一份
 * 就会漂 —— 而且漂了**没有任何测试会红**：
 *
 *   1. controlsStyles.ts   —— 断点决定哪些控件被藏起来
 *   2. fullscreenControls.ts —— 收起态那枚独立退出钮要跟着换位置
 *   3. tests/e2e/…        —— 真实浏览器里量「退出按钮出没出屏」
 *
 * 历史教训（2026-10-21）：断点原先写死在 CSS 里（500 / 380），
 * 而那对数是**估**的（490 / 365 / 293），不是量出来的。
 * 真实需求是 553 / 401 / 321 —— 于是 501–546px 与 381–400px
 * 这两段视口宽度里，**退出按钮被推出屏幕**：手机上鼠标点不到退出按钮，
 * 用户被关在全屏里，只能靠 Esc（而「按 Esc 能退」从没在界面上告诉过他）。
 *
 * 所以这里的数分两类，**不许混**：
 *
 *   CONTROL_BAR_REQUIRED_WIDTHS —— **实测**（真实 Chromium 量出来的）。
 *       每一档要装下自己那套控件，视口至少得这么宽。
 *   CONTROL_BAR_BREAKPOINTS —— **决策**（在实测值上留余量）。
 *       为什么留余量：断点落在「刚好装得下」那一点上时，差 1px 就溢出。
 *       余量留给滚动条、缩放、字体回退（系统没装 Inter 时字更宽）。
 */

/**
 * 各档的**实测**宽度需求（真实 Chromium，2026-10-21）。
 *
 * 量法：进网页全屏后读控制条里「退出」按钮的 getBoundingClientRect().right。
 * 这个数是**内容驱动**的 —— 视口再宽，它也不会更靠左；
 * 视口不够宽时，它会卡在同一个数上，于是按钮的右边缘就跑到屏幕外。
 *
 * ⚠️ 这些数是**最坏情况**下的：时长用「1:00:00 / 2:00:00」这种长字符串
 * 量过（短时长会窄 13.5px）。用短时长量出来的数会偏乐观，
 * 于是长视频一播出来就出屏 —— 而那正是最常见的场景。
 *
 * ⚠️ 语义：「这一档要装下自己那套控件，视口至少得这么宽，
 * **退出按钮才不会被推出屏幕**」。不是「还留得下右内边距」——
 * 后者是个锦上添花的要求，而前者是**能不能出去**的问题。
 *
 * ⚠️ 量的时候别用「这一档的起点」当需求：起点是**决策**（带余量），
 * 需求是**事实**。两者混了，断点就会再次被算错 —— 这正是本轮踩过的坑。
 */
export const CONTROL_BAR_REQUIRED_WIDTHS = {
  /** 完整一套（音量滑块 + 总时长都在）：退出按钮右边缘恒在 552.83px。 */
  full: 553,
  /** 去掉音量滑块与总时长：退出按钮右边缘恒在 400.33px。 */
  medium: 401,
  /** 紧凑一套（按钮 30px、间距 6px、进度条 60px）：退出按钮右边缘恒在 321px。 */
  compact: 321,
  /** 极简一套（连时间都不显示）：退出按钮右边缘恒在 234px。 */
  minimal: 234,
  /** 最后一档（连进度条与静音都让位）：只剩播放 / 倍速 / 退出，右边缘恒在 134px。 */
  narrowest: 134,
} as const;

/**
 * 各档的**断点**（决策值，在实测需求上留了余量）。
 *
 *   > 560px  → 完整一套（需 553，余 7px）
 *   ≤ 560px  → 去掉音量滑块与总时长（需 401，余 29px）
 *   ≤ 430px  → 紧凑一套（需 321，余 9px）
 *   ≤ 330px  → 连时间都不显示（需 234，余 6px）
 *   ≤ 240px  → 连进度条与静音都让位（需 134，余 6px）
 *
 * ⚠️ 最后两档是为「200% 放大」准备的：320px 的手机放到 200%
 * 就是 160px 的 CSS 视口，前三档都装不下 ——
 * 那时至少要把**退出按钮**保住（它是唯一的逃生口），
 * 时间显示、进度条、静音可以让位，但**倍速读数要留着**
 * （那是用户唯一能一眼看到「现在是几倍速」的地方）。
 *
 * ⚠️ 再窄（< 134px）就真的放不下了：那时退出按钮会出屏，
 * 但收起态那枚**独立退出钮**是 `position: fixed` 的（永远在屏内），
 * 加上 Esc 与 `f` 键，用户仍出得来。
 */
export const CONTROL_BAR_BREAKPOINTS = {
  /** 完整一套 → 中间一套（藏音量滑块与总时长）。 */
  medium: 560,
  /** 中间一套 → 紧凑一套（收紧 padding、按钮缩到 30px）。 */
  compact: 430,
  /** 紧凑一套 → 极简一套（连时间都不显示）。 */
  minimal: 330,
  /** 极简一套 → 最后一档（连进度条与静音都让位）。 */
  narrowest: 240,
} as const;

/**
 * 宽屏时控制条的内边距。
 *
 * 收起态那枚独立退出钮要落在控制条退出按钮的**同一个位置**，
 * 而控制条的 padding 决定那个位置 —— 所以这两个数必须和控制条 CSS 一致。
 *
 * ⚠️ **这里必须是唯一的出处**（2026-10-21 复审发现）：
 * 之前这一段写着「必须和控制条 CSS 一致」，可 CSS 那边是**字面量**
 * `padding: 20px 18px 12px` —— 两份数字、没有任何机制保证一致。
 * 于是只把这里的 `right` 从 18 改成 4（CSS 不动），收起态退出钮与
 * 控制条退出钮就**错开 14px**，而除了那条 1280px 宽的 e2e，没有任何测试会红。
 * 现在 CSS 的 padding 由这里拼出来，两边不可能再漂。
 */
export const CONTROL_BAR_WIDE_PADDING = { top: 20, right: 18, bottom: 12 } as const;

/**
 * 紧凑档（≤430px）时控制条的内边距。
 *
 * ⚠️ 这是**另一套**内边距，不是宽屏那套的减法 —— 窄屏档直接替换整个 padding。
 */
export const CONTROL_BAR_NARROW_PADDING = { top: 12, right: 10, bottom: 8 } as const;
